const {test,expect}=require('@playwright/test');
let pid,csrf,ownerContext;
test.describe.configure({mode:'serial'});
test('quill opens editor; real multi-file Typst compiles and saves in one history window',async({browser})=>{
  ownerContext=await browser.newContext();const page=await ownerContext.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')process.stdout.write('BROWSER '+m.text()+'\n');});
  const setup=await ownerContext.request.post('/api/v1/auth/setup',{data:{name:'Editor owner',email:'editor@example.org',password:'editor-test-password',sample_projects:false}});
  expect(setup.status()).toBe(201);csrf=(await setup.json()).csrf;
  const project=await ownerContext.request.post('/api/v1/projects',{headers:{'X-CSRF-Token':csrf},data:{title:'Typst editor integration'}});pid=(await project.json()).id;
  const upload=async(path,text)=>{const result=await ownerContext.request.put(`/api/v1/projects/${pid}/files/content?path=${encodeURIComponent(path)}`,{headers:{'X-CSRF-Token':csrf,'If-None-Match':'*','Content-Type':'application/octet-stream'},data:text});expect(result.ok()).toBeTruthy();};
  await upload('main.typ','= A manuscript\n\n#include "sections/proof.typ"\n\n$ sum_(i=1)^n i = (n(n+1))/2 $\n');
  await upload('sections/proof.typ','A proof using local project files.\n');
  await ownerContext.request.post(`/api/v1/projects/${pid}/files/commit`,{headers:{'X-CSRF-Token':csrf},data:{}});
  await page.goto(`/#project=${pid}`);
  await page.getByRole('button',{name:'Manuscript editor',exact:true}).click();
  await expect(page.getByRole('region',{name:'Manuscript editor',exact:true})).toBeVisible();
  await expect(page.getByRole('textbox',{name:'Manuscript source'})).toBeVisible();
  await expect(page.locator('#editor-build-status')).toContainText('1 page',{timeout:45000});
  await expect(page.locator('#editor-pages canvas')).toHaveCount(1);
  await expect(page.locator('#editor-download')).toHaveAttribute('href',/^blob:/);
  const input=page.getByRole('textbox',{name:'Manuscript source'});
  await input.click();await input.press('Control+End');await input.press('Enter');await input.pressSequentially('A first edit.');
  await expect(page.locator('#editor-save-status')).toContainText('Saved');
  await input.pressSequentially(' A second edit.');
  await expect(page.locator('#editor-save-status')).toContainText('Saved');
  let listing=await (await ownerContext.request.get(`/api/v1/projects/${pid}/files`)).json();
  expect(listing.history.pending).toHaveLength(1);expect(listing.history.pending[0].window_id).toBeTruthy();
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await expect.poll(async()=>{const data=await (await ownerContext.request.get(`/api/v1/projects/${pid}/files`)).json();return data.history.pending[0].closed;}).toBe(true);
  await page.getByRole('button',{name:'sections/proof.typ',exact:true}).click();
  await expect(page.locator('#editor-path')).toHaveText('sections/proof.typ');
  await expect(page.getByLabel('Main document')).toHaveValue('main.typ');
  await page.getByRole('button',{name:'Recompile',exact:true}).click();
  await expect(page.locator('#editor-build-status')).toContainText('1 page');
  expect(errors).toEqual([]);
  await page.close();
});

test('two browsers co-edit; idle, external replacement, and source download preserve the file model',async({browser})=>{
  const owner=await ownerContext.newPage();await owner.goto(`/#project=${pid}&view=editor&file=main.typ`);
  await expect(owner.getByRole('textbox',{name:'Manuscript source'})).toBeVisible();
  const invite=await ownerContext.request.post(`/api/v1/projects/${pid}/invitations`,{headers:{'X-CSRF-Token':csrf},data:{email:'coeditor@example.org'}});
  const otherContext=await browser.newContext();
  const account=await otherContext.request.post('/api/v1/auth/register',{data:{token:(await invite.json()).token,name:'Coeditor',email:'coeditor@example.org',password:'another-editor-password'}});expect(account.ok()).toBeTruthy();
  const other=await otherContext.newPage();await other.goto(`/#project=${pid}&view=editor&file=main.typ`);
  const input=owner.getByRole('textbox',{name:'Manuscript source'});await input.click();await input.press('Control+End');await input.pressSequentially('\nShared writing.');
  await expect(other.getByRole('textbox',{name:'Manuscript source'})).toContainText('Shared writing.');
  await expect(owner.locator('#editor-save-status')).toContainText('Saved');
  await expect.poll(async()=>{const data=await (await ownerContext.request.get(`/api/v1/projects/${pid}/files`)).json();return data.history.pending.at(-1).closed;},{timeout:10000}).toBe(true);
  const latest=await (await ownerContext.request.get(`/api/v1/projects/${pid}/files/preview?path=main.typ`)).json();
  const replacement=await ownerContext.request.put(`/api/v1/projects/${pid}/files/content?path=main.typ`,{headers:{'X-CSRF-Token':csrf,'If-Match':latest.etag},data:'= Replaced through the ordinary file API\n'});expect(replacement.ok()).toBeTruthy();
  await expect(input).toContainText('Replaced through the ordinary file API',{timeout:15000});
  await expect(other.getByRole('textbox',{name:'Manuscript source'})).toContainText('Replaced through the ordinary file API',{timeout:15000});
  const source=await ownerContext.request.get('/api/v1/editor/source');expect(source.ok()).toBeTruthy();expect((await source.body()).subarray(0,2).toString()).toBe('PK');
  await otherContext.close();await owner.close();await ownerContext.close();
});
